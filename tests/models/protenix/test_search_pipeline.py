def _write_fake_kalign(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, *, version: str = "3.3.5"
) -> Path:
    binary = tmp_path / f"kalign-{version}"
    binary.write_text(
        "#!/usr/bin/env python3\n"
        "import pathlib\n"
        "import sys\n"
        "if '--version' in sys.argv:\n"
        f"    print('kalign {version}')\n"
        "    raise SystemExit(0)\n"
        "input_path = pathlib.Path(sys.argv[sys.argv.index('-i') + 1])\n"
        "output_path = pathlib.Path(sys.argv[sys.argv.index('-o') + 1])\n"
        "output_path.write_text(input_path.read_text())\n"
    )
    binary.chmod(0o755)
    monkeypatch.setenv("PROTENIX_KALIGN_BINARY", str(binary))
    return binary


def _write_seqres_mmcif(path: Path, *, chain_id: str, sequence: str) -> None:
    rows = "\n".join(
        f"1 {index} {_PROTEIN_1TO3[residue]}"
        for index, residue in enumerate(sequence, start=1)
    )
    path.write_text(
        f"data_{path.stem}\n"
        "loop_\n"
        "_entity_poly_seq.entity_id\n"
        "_entity_poly_seq.num\n"
        "_entity_poly_seq.mon_id\n"
        f"{rows}\n"
        "loop_\n"
        "_struct_asym.id\n"
        "_struct_asym.entity_id\n"
        "A 1\n"
        "loop_\n"
        "_atom_site.label_asym_id\n"
        "_atom_site.auth_asym_id\n"
        "_atom_site.pdbx_PDB_model_num\n"
        f"A {chain_id} 1\n"
    )


class RecordingBackend:
    name = "fake"
    version = "db-2026-01"

    def __init__(self, payload: MsaPayload) -> None:
        self.payload = payload
        self.calls: list[str] = []

    def search(self, sequence: str) -> MsaPayload:
        self.calls.append(sequence)
        return self.payload


class RecordingRnaBackend:
    name = "fake-rna"
    version = "rna-db-2026"

    def __init__(self) -> None:
        self.calls: list[str] = []

    def search(self, sequence: str) -> RnaMsaPayload:
        self.calls.append(sequence)
        return RnaMsaPayload(
            unpaired=f">query\n{sequence}\n>hit\n{sequence[:-1]}-\n",
            source={"databases": ["rfam", "rnacentral", "nt-rna"]},
        )


def test_msa_pipeline_writes_paths_provenance_and_reuses_cache(tmp_path: Path) -> None:
    backend = RecordingBackend(
        MsaPayload(
            paired=">query\nACDE\n>paired\nACDE\n",
            unpaired=">query\nACDE\n>hit\nAC-E\n",
            source={"job_id": "job-7", "database": "uniref30-2026-01"},
        )
    )
    pipeline = MsaSearchPipeline(tmp_path, backend, options={"mode": "complete"})

    first = pipeline.search(["acde", "ACDE"])
    second = pipeline.search(["ACDE"])

    assert backend.calls == ["ACDE"]
    assert first[0] == first[1] == second[0]
    assert first[0]["pairedMsaPath"].endswith("/pairing.a3m")
    assert first[0]["unpairedMsaPath"].endswith("/non_pairing.a3m")
    provenance = json.loads(Path(first[0]["provenancePath"]).read_text())
    assert provenance["sequence_sha256"] != provenance["cache_key"]
    assert provenance["backend"] == {"name": "fake", "version": "db-2026-01"}
    assert provenance["options"] == {"mode": "complete"}
    assert provenance["source"]["job_id"] == "job-7"
    assert provenance["files"]["pairing.a3m"]["sha256"]


