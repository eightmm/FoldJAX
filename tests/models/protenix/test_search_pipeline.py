def test_template_resolution_rejects_a_kalign_below_the_floor(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Newer is allowed now; older is still refused.

    This asserted that 3.6.0 was rejected, which was the exact pin talking. The
    floor is what protects the alignment, and PyPI's wheel starts at 3.4.8, so
    an exact pin only made templates unreachable without a system package.
    """
    binary = _write_fake_kalign(tmp_path, monkeypatch, version="3.3.4")
    database = tmp_path / "mmcif"
    database.mkdir()
    query = "ACDEFGHIKLMN"
    _write_seqres_mmcif(database / "1abc.cif", chain_id="A", sequence=query)
    artifact = tmp_path / "hits.a3m"
    artifact.write_text(
        f">query\n{query}\n>1abc_A mol:protein 1-12 hit\n{'Y' * len(query)}\n"
    )
    release_dates = tmp_path / "release_dates.json"
    release_dates.write_text(json.dumps({"1abc": {"release_date": "2020-01-01"}}))
    obsolete = tmp_path / "obsolete.json"
    obsolete.write_text("{}")

    with pytest.raises(RuntimeError, match=r"requires Kalign 3\.3\.5.*3\.3\.4"):
        resolve_template_search_hits(
            artifact,
            query_sequence=query,
            mmcif_dir=database,
            release_dates_path=release_dates,
            obsolete_pdbs_path=obsolete,
            kalign_binary=binary,
        )


def _hhr_hit(
    index: int,
    name: str,
    hit_sequence: str,
    sum_probs: float,
    *,
    aligned_cols: int | None = None,
) -> str:
    query = "ACDEFGHIKLMNPQRSTVWY"[: len(hit_sequence)]
    cols = len(hit_sequence) if aligned_cols is None else aligned_cols
    return (
        f"No {index}\n"
        f">{name} synthetic\n"
        f"Probab=99.0 Aligned_cols={cols} Sum_probs={sum_probs}\n"
        f"Q query            1 {query} {len(query)} ({len(query)})\n"
        f"T {name:<16} 1 {hit_sequence} {len(hit_sequence)} "
        f"({len(hit_sequence)})\n"
    )


