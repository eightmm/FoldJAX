def test_remote_client_mock_transport_happy_path() -> None:
    def archive(files: dict[str, str]) -> bytes:
        buffer = io.BytesIO()
        with tarfile.open(fileobj=buffer, mode="w:gz") as output:
            for name, content in files.items():
                raw = content.encode()
                info = tarfile.TarInfo(name)
                info.size = len(raw)
                output.addfile(info, io.BytesIO(raw))
        return buffer.getvalue()

    unpaired = archive(
        {
            "uniref.a3m": ">101\nACDE\n>hit\nAC-E\n",
            "bfd.mgnify30.metaeuk30.smag30.a3m": ">101\nACDE\n",
        }
    )
    paired = archive({"pair.a3m": ">101\nACDE\n>pair\nACDE\n"})
    responses = iter(
        [
            HttpResponse(200, b'{"status":"COMPLETE","id":"u-1"}'),
            HttpResponse(200, unpaired),
            HttpResponse(200, b'{"status":"COMPLETE","id":"p-1"}'),
            HttpResponse(200, paired),
        ]
    )
    requests: list[tuple[str, str]] = []

    def transport(method: str, url: str, *_: object) -> HttpResponse:
        requests.append((method, url))
        return next(responses)

    payload = RemoteMMseqs2Client(
        "https://msa.invalid/api", version="api-v1", transport=transport
    ).search("ACDE")

    assert payload.source == {"paired_job_id": "p-1", "unpaired_job_id": "u-1"}
    assert payload.paired.startswith(">101\nACDE")
    assert requests == [
        ("POST", "https://msa.invalid/api/ticket/msa"),
        ("GET", "https://msa.invalid/api/result/download/u-1"),
        ("POST", "https://msa.invalid/api/ticket/pair"),
        ("GET", "https://msa.invalid/api/result/download/p-1"),
    ]


