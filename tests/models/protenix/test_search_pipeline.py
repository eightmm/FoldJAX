def test_official_opendde_template_mappings_and_features_match_hashes(
    example_json: str,
    artifact_path: str,
    expected: list[tuple[str, str, str, str]],
) -> None:
    binary = os.environ.get("PROTENIX_KALIGN_BINARY")
    if binary is None:
        pytest.skip("set PROTENIX_KALIGN_BINARY to the pinned Kalign 3.3.5 binary")
    workspace = Path(__file__).resolve().parents[4]
    examples = workspace / "OpenDDE/examples/examples_with_template"
    database = workspace / "opendde_jax/weights/template_mmcif"
    release_dates = workspace / "protenix/common/release_date_cache.json"
    obsolete = workspace / "protenix/common/obsolete_to_successor.json"
    required = [examples / example_json, examples / artifact_path, database]
    if not all(path.exists() for path in [*required, release_dates, obsolete]):
        pytest.skip("official OpenDDE template examples/assets are unavailable")
    job = json.loads((examples / example_json).read_text())[0]
    query = job["sequences"][0]["proteinChain"]["sequence"]

    resolved = resolve_template_search_hits(
        examples / artifact_path,
        query_sequence=query,
        mmcif_dir=database,
        release_dates_path=release_dates,
        obsolete_pdbs_path=obsolete,
        kalign_binary=binary,
    )

    actual: list[tuple[str, str, str, str]] = []
    for template in resolved:
        mapping = dict(
            zip(
                template["queryIndices"],
                template["templateIndices"],
                strict=True,
            )
        )
        mapping_digest = hashlib.sha256(
            json.dumps(sorted(mapping.items()), separators=(",", ":")).encode()
        ).hexdigest()
        features = _single_json_template(template, len(query))
        feature_hasher = hashlib.sha256()
        feature_hasher.update(
            np.asarray(features["template_aatype"], dtype="<i4").tobytes()
        )
        feature_hasher.update(
            np.asarray(features["template_all_atom_positions"], dtype="<f4").tobytes()
        )
        feature_hasher.update(
            np.asarray(features["template_all_atom_masks"], dtype="<f4").tobytes()
        )
        actual.append(
            (
                template["pdbId"],
                template["chainId"],
                mapping_digest,
                feature_hasher.hexdigest(),
            )
        )
    assert actual == expected


def test_local_template_search_pipeline_caches_and_applies_paths(
    tmp_path: Path,
) -> None:
    calls = []

    def runner(command: list[str], **_: object):
        calls.append(command)
        output = Path(command[command.index("--output") + 1])
        (output / "templates.a3m").write_text(
            ">query\nACDEF\n>1abc_A mol:protein 1-5\nACDEF\n"
        )
        return type("Completed", (), {"returncode": 0, "stdout": "", "stderr": ""})()

    msa = tmp_path / "query.a3m"
    msa.write_text(">query\nACDEF\n")
    backend = LocalTemplateSearchClient(
        ["fake-template-wrapper"], version="pdb-2026", runner=runner
    )
    pipeline = TemplateSearchPipeline(tmp_path / "cache", backend)
    inference = {
        "sequences": [
            {"proteinChain": {"sequence": "ACDEF", "unpairedMsaPath": str(msa)}}
        ]
    }
    first = apply_template_paths(inference, pipeline)
    second = apply_template_paths(inference, pipeline)
    path = first["sequences"][0]["proteinChain"]["templatesPath"]
    assert path == second["sequences"][0]["proteinChain"]["templatesPath"]
    assert len(calls) == 1
    assert Path(path).name == "templates.a3m"
    provenance = json.loads((Path(path).parent / "provenance.json").read_text())
    assert provenance["backend"] == {"name": "local-template", "version": "pdb-2026"}


